import React, { useState, useRef, useEffect } from 'react';
import { scrollMainToTop } from '../utils/scrollTop';
import { generateStudyContent } from '../services/geminiService';
import BookLoader from './BookLoader';
import MarkdownContent from './MarkdownContent';
import SaveToFolderModal from './SaveToFolderModal';
import { QuizFolder, QuizQuestion, StudyProfile, EditalConfig, ExplanationStyle } from '../types';
import EditalToggle from './EditalToggle';

interface AIViewProps {
  onBack: () => void;
  folders: QuizFolder[];
  onNewContent: (content: any) => void;
  onSaveToNotebook: (folderId: string, notebookName: string, questions: QuizQuestion[], summary?: string, notebookColor?: string, folderColor?: string) => void;
  studyProfile: StudyProfile;
  prefill?: { topic: string; autoStart: boolean } | null;
  onConsumedPrefill?: () => void;
  strategicMode?: boolean;
  editalConfig?: EditalConfig;
  /** Liga/desliga o modo edital; guardado no App, por isso vale em qualquer tela e sobrevive ao recarregar. */
  onModoEdital?: (ligado: boolean) => void;
  explanationStyle?: ExplanationStyle;
  /** Leva o tema da aula para o TDHQuestões, onde as questões são conferidas. */
  onPracticeTopic?: (topic: string) => void;
}

const AIView: React.FC<AIViewProps> = ({ onBack, onNewContent, onSaveToNotebook, folders, studyProfile, prefill, onConsumedPrefill, strategicMode, editalConfig, onModoEdital, explanationStyle: initialStyle, onPracticeTopic }) => {
  const [topic, setTopic] = useState(prefill?.topic || '');
  // Matéria separada do assunto. Além de ficar mais claro para o aluno, a busca de
  // fontes (functions/_lib/fontes.ts) separa no dois-pontos e usa a parte depois dele
  // como o tema específico — então "Direito Penal: legítima defesa" procura melhor do
  // que a frase inteira. A matéria é opcional: só o assunto já gera.
  const [subject, setSubject] = useState('');
  // O que de fato foi gerado, que nem sempre e o que esta digitado: no modo estrategico
  // vem do edital, e numa prefill vem de outra tela. O titulo e o salvar usam isto.
  const [temaGerado, setTemaGerado] = useState(prefill?.topic || '');
  const temaComposto = () => {
    const m = subject.trim();
    const a = topic.trim();
    return m && a ? `${m}: ${a}` : a;
  };
  const [selectedSubject, setSelectedSubject] = useState<string>('');
  const [selectedTopic, setSelectedTopic] = useState<string>('');
  const [loading, setLoading] = useState(false);
  const [result, setResult] = useState<any>(null);
  const [saved, setSaved] = useState(false);
  const [showSaveModal, setShowSaveModal] = useState(false);
  const [explanationStyle, setExplanationStyle] = useState<ExplanationStyle>(initialStyle || 'TECNICA');
  const [generatingCards, setGeneratingCards] = useState(false);
  const [loadError, setLoadError] = useState<string | null>(null);
  const requestIdRef = useRef(0);
  // The dossier has a light and a dark look; the markdown renderer needs to know which one is active.
  const [isDark, setIsDark] = useState(() => document.documentElement.classList.contains('dark'));
  useEffect(() => {
    const root = document.documentElement;
    const observer = new MutationObserver(() => setIsDark(root.classList.contains('dark')));
    observer.observe(root, { attributes: true, attributeFilter: ['class'] });
    return () => observer.disconnect();
  }, []);
  // Trocar entre formulário, "Preparando…" e resultado volta ao topo (antes abria rolado).
  useEffect(() => { scrollMainToTop(); }, [loading, !!result]);

  React.useEffect(() => {
    if (prefill?.autoStart && prefill.topic) {
      handleGenerate(prefill.topic);
      onConsumedPrefill?.();
    }
  }, [prefill]);

  const handleGenerate = async (targetTopic?: string) => {
    const finalTopic = targetTopic || (strategicMode ? (selectedTopic ? `${selectedSubject}: ${selectedTopic}` : '') : temaComposto());
    if (!finalTopic.trim()) return;

    setLoading(true);
    setLoadError(null);
    const requestId = ++requestIdRef.current;
    if (!targetTopic) setResult(null); // Reset total se for busca nova
    setSaved(false);

    try {
      const content = await Promise.race([
        generateStudyContent(finalTopic, 'Dossiê Expandido', 0, studyProfile, explanationStyle),
        new Promise<never>((_, reject) => setTimeout(() => reject(new Error('__TIMEOUT__')), 45000)),
      ]);
      if (requestId !== requestIdRef.current) return; // resposta atrasada de uma tentativa já abandonada
      // We filter out flashcards if they were auto-generated by the service, as per user's request
      // But looking at the service, it's baked into the schema.
      // We will keep them in the result object but not call onNewContent immediately if we want to separate logic.
      // However, onNewContent in App.tsx adds to flashcards state.
      // The user wants AI cards only when asked.

      const contentWithoutAutoCards = { ...content, flashcards: [] };
      setResult(content); // Keep them in state but maybe don't "activate" them yet
      setTemaGerado(finalTopic);
      if (targetTopic) setTopic(targetTopic);
      onNewContent(contentWithoutAutoCards);
      window.scrollTo({ top: 0, behavior: 'smooth' });
    } catch (error: any) {
      if (requestId !== requestIdRef.current) return;
      console.error(error);
      setLoadError(error?.message === '__TIMEOUT__'
        ? 'A geração está demorando mais que o normal (mais de 45 segundos). Pode ser instabilidade da IA ou da conexão.'
        : (error?.message || 'Não foi possível gerar o material. Tente novamente.'));
    } finally {
      if (requestId === requestIdRef.current) setLoading(false);
    }
  };

  const handleGenerateFlashcards = async () => {
    if (!result || !topic.trim()) return;
    setGeneratingCards(true);

    try {
      // Actually generate a fresh batch of study content for the current topic
      // and take only the new flashcards from it (geminiService has no more
      // targeted "flashcards only" export, so we reuse generateStudyContent).
      const freshContent = await generateStudyContent(topic, 'Dossiê Expandido', 0, studyProfile, explanationStyle);
      setResult((prev: any) => (prev ? { ...prev, flashcards: freshContent.flashcards } : prev));
      onNewContent({ ...freshContent, quiz: [] }); // Only send flashcards
      alert('Flashcards gerados e adicionados à sua revisão!');
    } catch (error: any) {
      console.error(error);
      const msg = error.message || 'Erro ao gerar flashcards. Tente novamente.';
      alert(msg);
    } finally {
      setGeneratingCards(false);
    }
  };

  const handleConfirmSave = (folderId: string, notebookName: string, notebookColor: string, folderColor: string) => {
    if (result) {
      onSaveToNotebook(folderId, notebookName, result.quiz, result.executiveSummary, notebookColor, folderColor);
      setSaved(true);
      setShowSaveModal(false);
    }
  };

  const canGenerate = strategicMode ? Boolean(selectedSubject && selectedTopic) : topic.trim().length > 0;

  if (loading) {
    return (
      <div className="relative isolate w-full min-h-[calc(100dvh-8rem)] rounded-[32px] bg-[#473c33] text-white selection:bg-amber-300/30 p-3 sm:p-6">
        <div className="relative h-full min-h-[calc(100dvh-11rem)] w-full overflow-hidden rounded-[28px] border border-white/10 shadow-2xl flex flex-col items-center justify-center gap-6 animate-in fade-in duration-500">
          <BookLoader className="scale-[2.4] sm:scale-[3]" />
          <div className="text-center px-6 mt-4">
            <p className="text-white font-black text-xl tracking-tight drop-shadow-md">Preparando seu material...</p>
            <p className="text-white/70 text-[10px] font-bold uppercase tracking-[0.22em] leading-relaxed mt-2">A IA está organizando a explicação e os exemplos.</p>
          </div>
          <div className="absolute inset-x-0 top-0 z-20 flex items-center justify-between gap-4 p-4 sm:p-5 bg-[#473c33]/55 backdrop-blur-md border-b border-white/10">
            <button onClick={onBack} className="shrink-0 p-2.5 rounded-xl text-white/70 hover:text-white hover:bg-white/10 transition-all" aria-label="Voltar ao painel" title="Voltar">
              <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24">
                <path d="M15 19l-7-7 7-7" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round" />
              </svg>
            </button>
            <div className="min-w-0 flex-1 text-center sm:text-left">
              <p className="text-[9px] font-black uppercase tracking-[0.3em] text-[#fed386]">{strategicMode ? (studyProfile === 'FACULDADE' ? 'ESTUDO PELA GRADE' : 'ESTUDO PELO EDITAL') : 'ESTUDO POR TEMA'}</p>
              <h1 className="mt-1 text-sm sm:text-base font-black text-white truncate">Preparando seu material</h1>
            </div>
            <div className="hidden sm:flex items-center gap-2 shrink-0 text-[9px] font-black uppercase tracking-widest text-white/60">
              <span className="w-2 h-2 rounded-full bg-[#fecc73] animate-pulse" />
              Processando
            </div>
          </div>
        </div>
      </div>
    );
  }

  // Quatro peças de estilo em vez de repetir o mesmo ternário de isDark em cada elemento da tela de
  // resultado — era assim que ela estava, e por isso qualquer ajuste virava uma caçada.
  const caixa = isDark ? 'border-white/10 bg-white/5' : 'border-[#e9e0d4] bg-white';
  const tinta = isDark ? 'text-[#f2efd2]' : 'text-[#473c33]';
  const sutil = isDark ? 'text-slate-400' : 'text-[#6b5e50]';
  const rotulo = isDark ? 'text-[#fecc73]' : 'text-[#bd5628]';

  return (
    <div className={`relative isolate w-full min-h-full min-w-0 rounded-[32px] selection:bg-amber-300/30 font-sans ${result && isDark ? 'bg-[#473c33] text-white' : 'bg-[#f7f3ed] text-[#473c33]'}`}>
      {/* A folga de baixo é a do material gerado, que é longo. Na tela de
          começar ela só criava barra de rolagem num cartão que já cabia. */}
      <div className={`w-full max-w-7xl mx-auto px-4 sm:px-6 xl:px-10 animate-in fade-in slide-in-from-bottom-10 duration-700 ${result ? 'pt-6 sm:pt-10 pb-32' : 'pt-2 pb-2'}`}>
        {!result ? (
          /* Esta tela cabe inteira: nada aqui exige rolagem, e rolar para achar
             o botão de gerar era o começo de toda sessão de estudo. */
          <div className="w-full max-w-6xl mx-auto">
            <section className="overflow-hidden rounded-[32px] border border-[#e9e0d4] bg-white shadow-[0_18px_48px_rgba(71,60,51,0.14)]">
              <header className="flex flex-wrap items-center justify-between gap-3 border-b border-[#eee6d6] px-5 py-2 sm:px-7">
                <button onClick={onBack} className="inline-flex min-h-[44px] items-center gap-2 rounded-xl px-3 py-2 text-xs font-black uppercase tracking-[0.16em] text-[#8f8375] transition-colors hover:bg-[#f7f3ed] hover:text-[#473c33]">
                  <svg className="h-4 w-4" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2.5" d="M15 19l-7-7 7-7" /></svg>
                  Voltar
                </button>
                <div className="flex items-center gap-2 rounded-full bg-[#fff6e8] px-3 py-2 text-[10px] font-black uppercase tracking-[0.18em] text-[#8f5614] dark:text-[#f5a46f]">
                  <span className="h-2 w-2 animate-pulse rounded-full bg-[#f5b84b]" />
                  {strategicMode ? (studyProfile === 'FACULDADE' ? 'Estudo pela grade' : 'Estudo pelo edital') : 'Estudo por tema'}
                </div>
              </header>

              <div className="grid lg:grid-cols-[1.02fr_0.98fr]">
                <div className="flex flex-col justify-center bg-[#abc270] px-6 py-6 text-[#473c33] sm:px-10 sm:py-8">
                  <div className="flex h-11 w-11 items-center justify-center rounded-2xl bg-[#fecc73] text-[#473c33] shadow-lg shadow-black/10">
                    <svg className="h-5 w-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M12 6.253v13m0-13C10.832 5.477 9.246 5 7.5 5S4.168 5.477 3 6.253v13C4.168 18.477 5.754 18 7.5 18s3.332.477 4.5 1.253m0-13C13.168 5.477 14.754 5 16.5 5c1.747 0 3.332.477 4.5 1.253v13C19.832 18.477 18.247 18.5 16.5 18c-1.746 0-3.332.477-4.5 1.253" /></svg>
                  </div>
                  <p className="mt-5 text-[10px] font-black uppercase tracking-[0.3em] text-[#596b2a]">Material de estudo</p>
                  <h1 className="mt-2 max-w-md text-3xl font-black uppercase leading-[0.98] tracking-tight text-[#473c33]">{strategicMode ? (studyProfile === 'FACULDADE' ? 'Estudo pela grade' : 'Estudo pelo edital') : 'Estudo por tema'}</h1>
                  <p className="mt-3 max-w-md text-sm font-semibold leading-relaxed text-[#473c33]">{strategicMode ? (studyProfile === 'FACULDADE' ? 'Escolha uma disciplina da sua grade e um assunto para montar o material.' : 'Escolha uma matéria do seu edital e um assunto para montar o material.') : `Informe um tema para criar um material de estudo para ${studyProfile.toLowerCase()}, com resumo, análise e bizu de memória.`}</p>
                  {/* Os dois passos são orientação, não comando: numa janela
                      baixa eles saem para o formulário caber sem rolagem. */}
                  <div className="mt-5 grid gap-3 sm:grid-cols-2 [@media(max-height:780px)]:hidden">
                    <div className="rounded-2xl border border-[#f4f7ec]/70 bg-[#f4f7ec]/35 px-4 py-3">
                      <p className="text-[10px] font-black uppercase tracking-widest text-[#596b2a]">01 · Escolha o foco</p>
                      <p className="mt-1 text-xs font-medium text-[#596b2a]">Defina o tema ou selecione no edital.</p>
                    </div>
                    <div className="rounded-2xl border border-[#f4f7ec]/70 bg-[#f4f7ec]/35 px-4 py-3">
                      <p className="text-[10px] font-black uppercase tracking-widest text-[#596b2a]">02 · Crie seu material</p>
                      <p className="mt-1 text-xs font-medium text-[#596b2a]">Resumo, análise e bizu de memória.</p>
                    </div>
                  </div>
                </div>

                <div className="flex flex-col justify-center px-6 py-6 sm:px-10 sm:py-8">
                  <h2 className="mb-4 text-2xl font-black tracking-tight text-[#473c33]">Escolha o que vai estudar</h2>

                  {loadError && (
                    <div role="alert" className="mb-5 rounded-2xl border border-red-200 bg-red-50 p-4 text-sm font-semibold text-red-800">
                      <p>{loadError}</p>
                      <button type="button" onClick={() => handleGenerate(canGenerate ? undefined : topic)} disabled={!canGenerate} className="mt-3 min-h-[44px] rounded-full bg-[#e96f34] px-5 text-[11px] font-black uppercase tracking-widest text-white disabled:opacity-50">Tentar de novo</button>
                    </div>
                  )}

                  <EditalToggle editalConfig={editalConfig} modoEdital={!!strategicMode} onModoEdital={onModoEdital} studyProfile={studyProfile} className="mb-3" />
                  {strategicMode && editalConfig?.isActive ? (
                    <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
                      <label className="block">
                        <span className="mb-2 block text-[10px] font-black uppercase tracking-widest text-[#725442]">{studyProfile === 'FACULDADE' ? 'Disciplina da grade' : 'Matéria do edital'}</span>
                        <select
                          value={selectedSubject}
                          onChange={(e) => {
                            setSelectedSubject(e.target.value);
                            setSelectedTopic('');
                          }}
                          className="w-full appearance-none rounded-2xl border border-[#e3d9ca] bg-[#fdfbf7] px-4 py-3 text-sm font-semibold text-[#473c33] outline-none transition-all focus:border-[#f5b84b] focus:ring-4 focus:ring-[#f5b84b]/15"
                        >
                          <option value="">Selecionar matéria...</option>
                          {editalConfig.subjects.map((s, i) => <option key={i} value={s.name}>{s.name}</option>)}
                        </select>
                      </label>
                      <label className="block">
                        <span className="mb-2 block text-[10px] font-black uppercase tracking-widest text-[#725442]">Assunto específico</span>
                        <select value={selectedTopic} onChange={(e) => setSelectedTopic(e.target.value)} disabled={!selectedSubject} className="w-full appearance-none rounded-2xl border border-[#e3d9ca] bg-[#fdfbf7] px-4 py-3 text-sm font-semibold text-[#473c33] outline-none transition-all focus:border-[#f5b84b] focus:ring-4 focus:ring-[#f5b84b]/15 disabled:cursor-not-allowed disabled:opacity-50">
                          <option value="">Selecionar assunto...</option>
                          {editalConfig.subjects.find((s) => s.name === selectedSubject)?.topics.map((t, i) => <option key={i} value={t}>{t}</option>)}
                        </select>
                      </label>
                    </div>
                  ) : (
                    /* Matéria e assunto lado a lado, como já era no modo
                       edital: empilhados custavam 70px de altura por nada — são
                       dois campos curtos. */
                    <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
                      <label className="block">
                        <span className="mb-2 block text-[10px] font-black uppercase tracking-widest text-[#725442]">Matéria <span className="font-bold normal-case tracking-normal text-[#a79c8e]">(opcional)</span></span>
                        <input value={subject} onChange={(e) => setSubject(e.target.value)} placeholder="Ex.: Direito Penal" className="w-full rounded-2xl border border-[#e3d9ca] bg-[#fdfbf7] px-4 py-3 text-sm font-semibold text-[#473c33] outline-none transition-all placeholder:text-[#b7ac9e] focus:border-[#f5b84b] focus:ring-4 focus:ring-[#f5b84b]/15" onKeyDown={(e) => e.key === 'Enter' && canGenerate && handleGenerate()} />
                      </label>
                      <label className="block">
                        <span className="mb-2 block text-[10px] font-black uppercase tracking-widest text-[#725442]">Assunto</span>
                        <input value={topic} onChange={(e) => setTopic(e.target.value)} placeholder="Ex.: Legítima defesa" className="w-full rounded-2xl border border-[#e3d9ca] bg-[#fdfbf7] px-4 py-3 text-sm font-semibold text-[#473c33] outline-none transition-all placeholder:text-[#b7ac9e] focus:border-[#f5b84b] focus:ring-4 focus:ring-[#f5b84b]/15" onKeyDown={(e) => e.key === 'Enter' && canGenerate && handleGenerate()} />
                      </label>
                    </div>
                  )}


                  <label className="group mt-4 block">
                    <span className="mb-2 block text-[10px] font-black uppercase tracking-widest text-[#725442]">Estilo da explicação</span>
                    <textarea value={explanationStyle} onChange={(e) => setExplanationStyle(e.target.value)} placeholder="Ex.: Explique de forma simples, técnica e analítica." className="min-h-[64px] w-full resize-none rounded-2xl border border-[#e3d9ca] bg-[#fdfbf7] px-4 py-3 text-sm font-medium text-[#473c33] outline-none transition-all placeholder:text-[#b7ac9e] focus:border-[#f5b84b] focus:ring-4 focus:ring-[#f5b84b]/15" />
                  </label>

                  <button onClick={() => handleGenerate()} disabled={!canGenerate} className="mt-5 flex w-full items-center justify-center gap-2 rounded-2xl bg-[#473c33] px-5 py-3.5 text-xs font-black uppercase tracking-[0.18em] text-white shadow-[0_10px_20px_rgba(71,60,51,0.18)] transition-all hover:bg-[#5a493f] disabled:cursor-not-allowed disabled:bg-[#d9d0c4] disabled:text-[#a79c8e] disabled:shadow-none">
                    Gerar material
                    <svg className="h-5 w-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2.5" d="M13 7l5 5m0 0l-5 5m5-5H6" /></svg>
                  </button>
                </div>
              </div>
            </section>
          </div>
        ) : (
          <div className="mx-auto w-full max-w-6xl py-4">
            {/* Barra de ações. Antes "praticar", "flashcards" e os mapas eram três cartões gigantes numa
                coluna que só virava barra lateral a partir de 1536 px — abaixo disso iam todos para o fim da
                página, depois da comparação, longe de quem acabou de ler. E salvar no caderno não tinha
                botão nenhum: o modal e o handler existiam, mas nada chamava setShowSaveModal(true). */}
            <div className={`sticky top-0 z-10 mb-6 flex flex-wrap items-center gap-2 rounded-2xl border px-3 py-2.5 backdrop-blur-xl ${caixa}`}>
              <button onClick={() => setResult(null)} className={`inline-flex min-h-[40px] shrink-0 items-center gap-2 rounded-xl px-3 text-[10px] font-black uppercase tracking-widest transition-colors ${isDark ? 'text-slate-400 hover:bg-white/10 hover:text-white' : 'text-[#8f8375] hover:bg-[#f0e8dc] hover:text-[#473c33]'}`}>
                <svg className="h-4 w-4" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth="3" d="M15 19l-7-7 7-7" /></svg>
                Nova pesquisa
              </button>

              <p className={`min-w-0 flex-1 truncate text-[11px] font-black uppercase tracking-tight ${tinta}`}>{temaGerado || topic}</p>

              {/* No celular as ações viram uma tira que rola de lado: em quatro linhas empilhadas a barra
                  passava de 180 px e, sendo grudada no topo, comia um quarto da tela de leitura. */}
              <div className="flex w-full items-center gap-2 overflow-x-auto pb-0.5 [scrollbar-width:none] sm:w-auto sm:overflow-visible sm:pb-0 [&::-webkit-scrollbar]:hidden">
                <button onClick={() => onPracticeTopic?.(temaGerado || topic)} className="inline-flex min-h-[40px] shrink-0 items-center gap-2 rounded-xl bg-[#fec868] px-4 text-[10px] font-black uppercase tracking-widest text-[#473c33] transition-all hover:bg-[#ffb22a] active:scale-95">
                  Praticar questões
                </button>
                <button onClick={handleGenerateFlashcards} disabled={generatingCards} className={`inline-flex min-h-[40px] shrink-0 items-center gap-2 rounded-xl border px-4 text-[10px] font-black uppercase tracking-widest transition-all active:scale-95 disabled:opacity-50 ${isDark ? 'border-white/15 text-white hover:bg-white/10' : 'border-[#e3d9ca] text-[#473c33] hover:bg-[#f0e8dc]'}`}>
                  {generatingCards ? 'Criando...' : 'Criar flashcards'}
                </button>
                <button onClick={() => setShowSaveModal(true)} className={`inline-flex min-h-[40px] shrink-0 items-center gap-2 rounded-xl border px-4 text-[10px] font-black uppercase tracking-widest transition-all active:scale-95 ${saved ? 'border-[#b1c77b] text-[#5d7336]' : isDark ? 'border-white/15 text-white hover:bg-white/10' : 'border-[#e3d9ca] text-[#473c33] hover:bg-[#f0e8dc]'}`}>
                  {saved ? 'Salvo no caderno' : 'Salvar no caderno'}
                </button>
                <button onClick={onBack} className={`inline-flex min-h-[40px] shrink-0 items-center rounded-xl px-3 text-[10px] font-black uppercase tracking-widest transition-colors ${isDark ? 'text-slate-500 hover:text-white' : 'text-[#a79c8e] hover:text-[#473c33]'}`}>
                  Sair
                </button>
              </div>
            </div>

            <div className="grid items-start gap-6 lg:grid-cols-[minmax(0,1fr)_19rem]">
              <div className="min-w-0 space-y-6">
                {/* Resumo e ponto em destaque */}
                <article className={`overflow-hidden rounded-3xl border ${caixa}`}>
                  <div className={`border-b px-5 py-4 sm:px-7 ${isDark ? 'border-white/10' : 'border-[#efe6d6]'}`}>
                    <p className={`text-[10px] font-black uppercase tracking-[0.28em] ${rotulo}`}>Resumo executivo</p>
                    <h2 className={`mt-1.5 text-xl font-black uppercase leading-tight tracking-tight sm:text-2xl ${tinta}`}>{temaGerado || topic}</h2>
                  </div>
                  {/* Coluna de leitura: o texto vinha em corpo 24 numa largura de até 1280 px. */}
                  <div className="px-5 py-5 sm:px-7 sm:py-6">
                    <div className={`max-w-[46rem] text-[1.05rem] leading-[1.8] ${isDark ? 'text-slate-100' : 'text-[#40372f]'}`}>
                      <MarkdownContent content={result.executiveSummary} isDark={isDark} />
                    </div>
                  </div>

                  <div className={`border-t px-5 py-5 sm:px-7 sm:py-6 ${isDark ? 'border-white/10 bg-white/[0.03]' : 'border-[#efe6d6] bg-[#fdfbf7]'}`}>
                    <p className={`mb-3 text-[10px] font-black uppercase tracking-[0.28em] ${rotulo}`}>Ponto em destaque</p>
                    <div className={`max-w-[46rem] text-[1.05rem] leading-[1.8] ${isDark ? 'text-slate-100' : 'text-[#40372f]'}`}>
                      <MarkdownContent content={result.deepDive} isDark={isDark} />
                    </div>
                  </div>
                </article>

                {/* Comparação */}
                {result.comparison && (
                  <article className={`overflow-hidden rounded-3xl border ${caixa}`}>
                    <div className={`border-b px-5 py-4 sm:px-7 ${isDark ? 'border-white/10' : 'border-[#efe6d6]'}`}>
                      <p className={`text-[10px] font-black uppercase tracking-[0.28em] ${rotulo}`}>Um ao lado do outro</p>
                    </div>
                    <div className="grid gap-px sm:grid-cols-2" style={{ backgroundColor: isDark ? 'rgba(255,255,255,0.08)' : '#efe6d6' }}>
                      {[
                        { nome: result.comparison.leftConcept, dados: result.comparison.leftData, cor: isDark ? 'text-[#fdad74]' : 'text-[#a2561f]' },
                        { nome: result.comparison.rightConcept, dados: result.comparison.rightData, cor: tinta },
                      ].map((lado, i) => (
                        <div key={i} className={`space-y-3 px-5 py-5 sm:px-7 ${isDark ? 'bg-[#272019]' : 'bg-white'}`}>
                          <h4 className={`text-lg font-black uppercase leading-tight tracking-tight ${lado.cor}`}>{lado.nome}</h4>
                          <div className={`text-[0.98rem] leading-[1.75] ${isDark ? 'text-slate-200' : 'text-[#40372f]'}`}>
                            <MarkdownContent content={lado.dados?.desc || ''} isDark={isDark} />
                          </div>
                          {lado.dados?.example && (
                            <div className={`rounded-2xl border px-4 py-3 text-sm leading-relaxed ${isDark ? 'border-white/10 bg-white/5 text-slate-100' : 'border-[#efdbb9] bg-[#fff6e7] text-[#473c33]'}`}>
                              <span className={`mb-1 block text-[9px] font-black uppercase tracking-widest ${rotulo}`}>Exemplo prático</span>
                              {lado.dados.example}
                            </div>
                          )}
                        </div>
                      ))}
                    </div>
                  </article>
                )}
              </div>

              {/* Mapas de conexão: agora ao lado a partir de 1024 px, não só em telas de 1536. */}
              {result.explorationMenu?.length > 0 && (
                <aside className={`rounded-3xl border p-4 lg:sticky lg:top-20 ${caixa}`}>
                  <h3 className={`mb-3 px-1 text-[10px] font-black uppercase tracking-[0.28em] ${sutil}`}>Mapas de conexão</h3>
                  <div className="space-y-2">
                    {result.explorationMenu.map((item: any, idx: number) => (
                      <button key={idx} onClick={() => handleGenerate(item.topic)} className={`w-full rounded-2xl border p-3.5 text-left transition-all active:scale-[0.98] ${isDark ? 'border-white/10 bg-white/[0.04] hover:bg-white/10' : 'border-[#eee6d6] bg-[#fdfbf7] hover:bg-[#f0e8dc]'}`}>
                        <p className={`mb-1 text-xs font-black uppercase tracking-tight ${tinta}`}>{item.topic}</p>
                        <p className={`line-clamp-2 text-[11px] font-medium leading-relaxed ${sutil}`}>{item.description}</p>
                      </button>
                    ))}
                  </div>
                </aside>
              )}
            </div>
          </div>
        )}
      </div>

      {showSaveModal && <SaveToFolderModal folders={folders} suggestedName={temaGerado || topic} onConfirm={handleConfirmSave} onClose={() => setShowSaveModal(false)} />}
    </div>
  );
};

export default AIView;
